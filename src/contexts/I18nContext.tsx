export interface I18nContextValue {
  t: (key: string, ns?: Namespaces, fallback?: string) => string;
  tCategory: (cat: string) => string;
  language: string;
  changeLanguage: (lng: string) => void;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const { language, setLanguage } = usePreferences();
  const resolvedLang = (language === "hi" || language === "mr" ? language : "en") as "en" | "hi" | "mr";

  const value = useMemo<I18nContextValue>(() => ({
    t: (key: string, ns?: Namespaces, fallback?: string): string => {
      if (!key) return "";
      // 1. If namespace is provided and match exists in current language
      if (ns && translations[resolvedLang]?.[ns]?.[key]) {
        return translations[resolvedLang][ns][key];
      }

      // 2. Search all namespaces in current language
      const currentDict = translations[resolvedLang];
      if (currentDict) {
        for (const n of Object.keys(currentDict) as Namespaces[]) {
          if (currentDict[n]?.[key]) {
            return currentDict[n][key];
          }
        }
      }

      // 3. Fall back to English namespace
      if (ns && translations.en[ns]?.[key]) {
        return translations.en[ns][key];
      }

      // 4. Fall back to any English namespace
      for (const n of Object.keys(translations.en) as Namespaces[]) {
        if (translations.en[n]?.[key]) {
          return translations.en[n][key];
        }
      }

      // 5. Explicit fallback or key itself
      return fallback !== undefined ? fallback : key;
    },
    tCategory: (cat: string): string => {
      if (!cat) return "";
      return (
        translations[resolvedLang]?.categories?.[cat] ||
        translations.en?.categories?.[cat] ||
        cat
      );
    },
    language: resolvedLang,
    changeLanguage: (lng: string) => {
      setLanguage(lng);
    },
  }), [resolvedLang, setLanguage]);

  return (
    <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextValue => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
};
